-- Trigger: keep CUSTOMERS CREDIT_AVAILABLE consistent
-- CREDIT_AVAILABLE is computed: CREDIT_LIMIT - CREDIT_USED (not stored, computed in query)
-- Trigger validates CREDIT_USED never exceeds CREDIT_LIMIT
CREATE OR ALTER TRIGGER TRG_CUSTOMERS_CREDIT_GUARD
ON CUSTOMERS
AFTER UPDATE
AS
BEGIN
  SET NOCOUNT ON;
  IF EXISTS (SELECT 1 FROM inserted WHERE CREDIT_USED > CREDIT_LIMIT)
  BEGIN
    RAISERROR('CREDIT_USED cannot exceed CREDIT_LIMIT', 16, 1);
    ROLLBACK;
  END;
  UPDATE CUSTOMERS SET UPDATED_AT = GETUTCDATE()
  FROM CUSTOMERS c INNER JOIN inserted i ON c.ID = i.ID;
END;
GO

-- Trigger: auto-update SALES aggregate on CASH_REGISTER when sale inserted
-- NOTE: The service layer handles this. Trigger is a safety net.
CREATE OR ALTER TRIGGER TRG_SALES_UPDATE_REGISTER_TOTALS
ON SALES
AFTER INSERT
AS
BEGIN
  SET NOCOUNT ON;
  UPDATE CASH_REGISTERS
  SET
    TOTAL_SALES    = TOTAL_SALES    + i.TOTAL,
    SALES_COUNT    = SALES_COUNT    + 1,
    CASH_SALES     = CASH_SALES     + CASE WHEN i.PAYMENT_METHOD = 'CASH'     THEN i.TOTAL ELSE 0 END,
    CARD_SALES     = CARD_SALES     + CASE WHEN i.PAYMENT_METHOD = 'CARD'     THEN i.TOTAL ELSE 0 END,
    TRANSFER_SALES = TRANSFER_SALES + CASE WHEN i.PAYMENT_METHOD = 'TRANSFER' THEN i.TOTAL ELSE 0 END,
    UPDATED_AT     = GETUTCDATE()
  FROM CASH_REGISTERS cr
  INNER JOIN inserted i ON cr.ID = i.CASH_REGISTER_ID
  WHERE i.CASH_REGISTER_ID IS NOT NULL
    AND i.IS_VOIDED = 0;
END;
GO

