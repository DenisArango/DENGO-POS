  UPDATED_AT   DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_CUSTOMERS_NIT  ON CUSTOMERS(NIT);
CREATE INDEX IX_CUSTOMERS_NAME ON CUSTOMERS(NAME);
GO

-- ── Suppliers ─────────────────────────────────────────────────
CREATE TABLE SUPPLIERS (
  ID            NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  CODE          NVARCHAR(30)  NOT NULL  UNIQUE,
  NAME          NVARCHAR(150) NOT NULL,
  CONTACT_NAME  NVARCHAR(150) NOT NULL  DEFAULT '',
  EMAIL         NVARCHAR(150)     NULL,
  PHONE         NVARCHAR(30)      NULL,
  ADDRESS       NVARCHAR(300)     NULL,
  CITY          NVARCHAR(100)     NULL,
  TAX_ID        NVARCHAR(30)      NULL,  -- NIT/RFC
  PAYMENT_TERMS NVARCHAR(50)  NOT NULL  DEFAULT 'Contado',
