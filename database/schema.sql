  RECEIVED_DATE DATETIME2(7)      NULL,
  NOTES         NVARCHAR(MAX)     NULL,
  CREATED_BY_ID NVARCHAR(36)  NOT NULL  REFERENCES USERS(ID),
  RECEIVED_BY_ID NVARCHAR(36)     NULL  REFERENCES USERS(ID),
