-- Close a cash register safely
CREATE OR ALTER PROCEDURE SP_CLOSE_CASH_REGISTER
  @REGISTER_ID   NVARCHAR(36),
  @CLOSED_BY_ID  NVARCHAR(36),
  @FINAL_AMOUNT  DECIMAL(18,2)
AS
BEGIN
  SET NOCOUNT ON;
  BEGIN TRANSACTION;
  BEGIN TRY
    DECLARE @INITIAL_AMOUNT  DECIMAL(18,2);
    DECLARE @TOTAL_MOVEMENTS DECIMAL(18,2);
    DECLARE @TOTAL_SALES     DECIMAL(18,2);
    DECLARE @EXPECTED_AMOUNT DECIMAL(18,2);

    SELECT
      @INITIAL_AMOUNT = INITIAL_AMOUNT,
      @TOTAL_SALES    = TOTAL_SALES
    FROM CASH_REGISTERS WHERE ID = @REGISTER_ID AND STATUS = 'OPEN';

    IF @@ROWCOUNT = 0
    BEGIN
      RAISERROR('Cash register not found or already closed', 16, 1);
      ROLLBACK;
      RETURN;
    END

    SELECT @TOTAL_MOVEMENTS = COALESCE(
      SUM(CASE WHEN TYPE = 'INCOME' THEN AMOUNT ELSE -AMOUNT END), 0
    )
    FROM CASH_MOVEMENTS WHERE CASH_REGISTER_ID = @REGISTER_ID;

    SET @EXPECTED_AMOUNT = @INITIAL_AMOUNT + @TOTAL_SALES + @TOTAL_MOVEMENTS;

    UPDATE CASH_REGISTERS SET
      STATUS          = 'CLOSED',
      CLOSED_BY_ID    = @CLOSED_BY_ID,
      CLOSED_AT       = GETUTCDATE(),
      FINAL_AMOUNT    = @FINAL_AMOUNT,
      EXPECTED_AMOUNT = @EXPECTED_AMOUNT,
      DIFFERENCE      = @FINAL_AMOUNT - @EXPECTED_AMOUNT,
      UPDATED_AT      = GETUTCDATE()
    WHERE ID = @REGISTER_ID;

    INSERT INTO AUDIT_LOGS (ID, USER_ID, ACTION, ENTITY, ENTITY_ID, CREATED_AT)
    VALUES (LOWER(NEWID()), @CLOSED_BY_ID, 'CLOSE', 'CASH_REGISTER', @REGISTER_ID, GETUTCDATE());

    COMMIT;
  END TRY
  BEGIN CATCH
    ROLLBACK;
    THROW;
  END CATCH;
END;
GO

-- Update inventory stock with movement record
CREATE OR ALTER PROCEDURE SP_UPDATE_STOCK
  @PRODUCT_ID      NVARCHAR(36),
  @BRANCH_ID       NVARCHAR(36),
  @DELTA           DECIMAL(18,4),
  @MOVEMENT_TYPE   NVARCHAR(20),
  @REASON          NVARCHAR(500),
  @PERFORMED_BY_ID NVARCHAR(36),
  @REFERENCE_ID    NVARCHAR(36)
AS
BEGIN
  SET NOCOUNT ON;
  BEGIN TRANSACTION;
  BEGIN TRY
    DECLARE @CURRENT_QTY DECIMAL(18,4) = 0;
    DECLARE @NEW_QTY     DECIMAL(18,4);
    DECLARE @INV_ID      NVARCHAR(36);

    SELECT @INV_ID = ID, @CURRENT_QTY = QUANTITY
    FROM INVENTORY
    WHERE PRODUCT_ID = @PRODUCT_ID AND BRANCH_ID = @BRANCH_ID;

    SET @NEW_QTY = CASE WHEN @CURRENT_QTY + @DELTA < 0 THEN 0 ELSE @CURRENT_QTY + @DELTA END;

    IF @INV_ID IS NULL
    BEGIN
      SET @INV_ID = LOWER(NEWID());
      INSERT INTO INVENTORY (ID, PRODUCT_ID, BRANCH_ID, QUANTITY, UPDATED_AT)
      VALUES (@INV_ID, @PRODUCT_ID, @BRANCH_ID, @NEW_QTY, GETUTCDATE());
    END
    ELSE
    BEGIN
      UPDATE INVENTORY
      SET QUANTITY        = @NEW_QTY,
          UPDATED_AT      = GETUTCDATE(),
          LAST_SALE_AT    = CASE WHEN @MOVEMENT_TYPE = 'SALE' THEN GETUTCDATE() ELSE LAST_SALE_AT    END,
          LAST_RESTOCK_AT = CASE WHEN @MOVEMENT_TYPE = 'IN'   THEN GETUTCDATE() ELSE LAST_RESTOCK_AT END
      WHERE ID = @INV_ID;
    END

    -- Update product sales counter for SALE type
    IF @MOVEMENT_TYPE = 'SALE'
      UPDATE PRODUCTS SET SALES_COUNT = SALES_COUNT + ABS(@DELTA), UPDATED_AT = GETUTCDATE()
      WHERE ID = @PRODUCT_ID;

    INSERT INTO STOCK_MOVEMENTS (
      ID, PRODUCT_ID, BRANCH_ID, TYPE, QUANTITY,
      QUANTITY_BEFORE, QUANTITY_AFTER, REASON, REFERENCE_ID, PERFORMED_BY_ID, CREATED_AT
    )
    VALUES (
      LOWER(NEWID()), @PRODUCT_ID, @BRANCH_ID, @MOVEMENT_TYPE, ABS(@DELTA),
      @CURRENT_QTY, @NEW_QTY, @REASON, @REFERENCE_ID, @PERFORMED_BY_ID, GETUTCDATE()
    );

    COMMIT;
  END TRY
  BEGIN CATCH
    ROLLBACK;
    THROW;
  END CATCH;
END;
GO
