-- ============================================================
--  SECTION 8 – TRIGGERS
-- ============================================================

-- Trigger: log product price changes
CREATE OR ALTER TRIGGER TRG_PRODUCTS_PRICE_AUDIT
ON PRODUCTS
AFTER UPDATE
AS
BEGIN
  SET NOCOUNT ON;
  -- Log BASE_PRICE change
  INSERT INTO PRICE_HISTORY (ID, PRODUCT_ID, FIELD, OLD_VALUE, NEW_VALUE, CHANGED_BY_ID, CREATED_AT)
  SELECT
    LOWER(NEWID()),
    i.ID,
    'BASE_PRICE',
    d.BASE_PRICE,
    i.BASE_PRICE,
    i.ID, -- CHANGED_BY_ID placeholder; service layer should log with real userId
    GETUTCDATE()
  FROM inserted i
  INNER JOIN deleted d ON i.ID = d.ID
  WHERE i.BASE_PRICE <> d.BASE_PRICE;

  -- Log COST change
  INSERT INTO PRICE_HISTORY (ID, PRODUCT_ID, FIELD, OLD_VALUE, NEW_VALUE, CHANGED_BY_ID, CREATED_AT)
  SELECT
    LOWER(NEWID()),
    i.ID,
    'COST',
    d.COST,
    i.COST,
    i.ID,
    GETUTCDATE()
  FROM inserted i
  INNER JOIN deleted d ON i.ID = d.ID
  WHERE i.COST <> d.COST;

  -- Update UPDATED_AT
  UPDATE PRODUCTS SET UPDATED_AT = GETUTCDATE()
  FROM PRODUCTS p INNER JOIN inserted i ON p.ID = i.ID;
END;
GO

