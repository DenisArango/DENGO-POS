-- ============================================================
--  SECTION 1 – CORE TABLES
-- ============================================================

-- ── Branches / Stores ────────────────────────────────────────
CREATE TABLE BRANCHES (
  ID               NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  NAME             NVARCHAR(150) NOT NULL,
  CODE             NVARCHAR(20)  NOT NULL  UNIQUE,
  TYPE             NVARCHAR(20)  NOT NULL  DEFAULT 'branch'  CHECK (TYPE IN ('main','branch')),
  ADDRESS          NVARCHAR(255) NOT NULL  DEFAULT '',
  CITY             NVARCHAR(100) NOT NULL  DEFAULT '',
  PHONE            NVARCHAR(30)  NOT NULL  DEFAULT '',
  EMAIL            NVARCHAR(150) NOT NULL  DEFAULT '',
  MANAGER          NVARCHAR(150) NOT NULL  DEFAULT '',
  STATUS           NVARCHAR(20)  NOT NULL  DEFAULT 'active'  CHECK (STATUS IN ('active','inactive','maintenance')),
  OPEN_TIME        NVARCHAR(5)   NOT NULL  DEFAULT '08:00',
  CLOSE_TIME       NVARCHAR(5)   NOT NULL  DEFAULT '20:00',
  -- Config (stored flat, avoid JSON for SQL Server compat)
  CURRENCY         NVARCHAR(10)  NOT NULL  DEFAULT 'GTQ',
  TIMEZONE         NVARCHAR(60)  NOT NULL  DEFAULT 'America/Guatemala',
  TAX_RATE         DECIMAL(5,4)  NOT NULL  DEFAULT 0.12,
  PRINTER_ENABLED  BIT           NOT NULL  DEFAULT 1,
  CREATED_AT       DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  UPDATED_AT       DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
GO

-- ── Users ─────────────────────────────────────────────────────
CREATE TABLE USERS (
  ID            NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  EMAIL         NVARCHAR(150) NOT NULL  UNIQUE,
  NAME          NVARCHAR(150) NOT NULL,
  PASSWORD_HASH NVARCHAR(255) NOT NULL,
  ROLE          NVARCHAR(30)  NOT NULL  CHECK (ROLE IN ('ADMIN','AUDITOR','INVENTORY_CONTROL','OPERATOR')),
  BRANCH_ID     NVARCHAR(36)  NOT NULL  REFERENCES BRANCHES(ID),
  IS_ACTIVE     BIT           NOT NULL  DEFAULT 1,
  CREATED_AT    DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  UPDATED_AT    DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_USERS_BRANCH_ID ON USERS(BRANCH_ID);
CREATE INDEX IX_USERS_EMAIL     ON USERS(EMAIL);
GO

-- ── Categories ────────────────────────────────────────────────
CREATE TABLE CATEGORIES (
  ID          NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  NAME        NVARCHAR(100) NOT NULL,
  DESCRIPTION NVARCHAR(500)     NULL,
  COLOR       NVARCHAR(30)      NULL,
  IS_ACTIVE   BIT           NOT NULL  DEFAULT 1,
  CREATED_AT  DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  UPDATED_AT  DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
GO

-- ── Product Units ─────────────────────────────────────────────
CREATE TABLE PRODUCT_UNITS (
  ID           NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  NAME         NVARCHAR(60)  NOT NULL,
  ABBREVIATION NVARCHAR(10)  NOT NULL,
  TYPE         NVARCHAR(20)  NOT NULL  CHECK (TYPE IN ('DISCRETE','CONTINUOUS')),
  CREATED_AT   DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
GO

-- ── Products ──────────────────────────────────────────────────
CREATE TABLE PRODUCTS (
  ID          NVARCHAR(36)   NOT NULL  PRIMARY KEY,
  BARCODE     NVARCHAR(50)       NULL  UNIQUE,
  SKU         NVARCHAR(50)       NULL,
  NAME        NVARCHAR(200)  NOT NULL,
  BRAND       NVARCHAR(100)      NULL,
  DESCRIPTION NVARCHAR(MAX)      NULL,
  BASE_PRICE  DECIMAL(18,2)  NOT NULL  DEFAULT 0,
  COST        DECIMAL(18,2)  NOT NULL  DEFAULT 0,
  IMAGE_URL   NVARCHAR(500)      NULL,
  CATEGORY_ID NVARCHAR(36)   NOT NULL  REFERENCES CATEGORIES(ID),
  BASE_UNIT_ID NVARCHAR(36)  NOT NULL  REFERENCES PRODUCT_UNITS(ID),
  MIN_STOCK   INT            NOT NULL  DEFAULT 0,
  SALES_COUNT INT            NOT NULL  DEFAULT 0,
  IS_ACTIVE   BIT            NOT NULL  DEFAULT 1,
  CREATED_AT  DATETIME2(7)   NOT NULL  DEFAULT GETUTCDATE(),
  UPDATED_AT  DATETIME2(7)   NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_PRODUCTS_CATEGORY_ID ON PRODUCTS(CATEGORY_ID);
CREATE INDEX IX_PRODUCTS_BARCODE     ON PRODUCTS(BARCODE) WHERE BARCODE IS NOT NULL;
CREATE INDEX IX_PRODUCTS_NAME        ON PRODUCTS(NAME);
GO

-- ── Product Variations ────────────────────────────────────────
CREATE TABLE PRODUCT_VARIATIONS (
  ID                NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  PRODUCT_ID        NVARCHAR(36)  NOT NULL  REFERENCES PRODUCTS(ID) ON DELETE CASCADE,
  NAME              NVARCHAR(100) NOT NULL,
  BARCODE           NVARCHAR(50)      NULL,
  CONVERSION_FACTOR DECIMAL(18,4) NOT NULL  DEFAULT 1,
  PRICE             DECIMAL(18,2) NOT NULL,
  IS_DEFAULT        BIT           NOT NULL  DEFAULT 0,
  CREATED_AT        DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_PRODUCT_VARIATIONS_PRODUCT_ID ON PRODUCT_VARIATIONS(PRODUCT_ID);
CREATE INDEX IX_PRODUCT_VARIATIONS_BARCODE    ON PRODUCT_VARIATIONS(BARCODE) WHERE BARCODE IS NOT NULL;
GO

-- ── Product Attributes ────────────────────────────────────────
CREATE TABLE PRODUCT_ATTRIBUTES (
  ID         NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  PRODUCT_ID NVARCHAR(36)  NOT NULL  REFERENCES PRODUCTS(ID) ON DELETE CASCADE,
  ATTR_NAME  NVARCHAR(100) NOT NULL,
  ATTR_VALUE NVARCHAR(255) NOT NULL
);
CREATE INDEX IX_PRODUCT_ATTRIBUTES_PRODUCT_ID ON PRODUCT_ATTRIBUTES(PRODUCT_ID);
GO

-- ── Inventory ─────────────────────────────────────────────────
CREATE TABLE INVENTORY (
  ID              NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  PRODUCT_ID      NVARCHAR(36)  NOT NULL  REFERENCES PRODUCTS(ID),
  BRANCH_ID       NVARCHAR(36)  NOT NULL  REFERENCES BRANCHES(ID),
  QUANTITY        DECIMAL(18,4) NOT NULL  DEFAULT 0,
  LAST_RESTOCK_AT DATETIME2(7)      NULL,
  LAST_SALE_AT    DATETIME2(7)      NULL,
  UPDATED_AT      DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  CONSTRAINT UQ_INVENTORY_PRODUCT_BRANCH UNIQUE (PRODUCT_ID, BRANCH_ID)
);
CREATE INDEX IX_INVENTORY_PRODUCT_ID ON INVENTORY(PRODUCT_ID);
CREATE INDEX IX_INVENTORY_BRANCH_ID  ON INVENTORY(BRANCH_ID);
GO

-- ── Stock Movements (complete audit trail) ────────────────────
CREATE TABLE STOCK_MOVEMENTS (
  ID              NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  PRODUCT_ID      NVARCHAR(36)  NOT NULL  REFERENCES PRODUCTS(ID),
  BRANCH_ID       NVARCHAR(36)  NOT NULL  REFERENCES BRANCHES(ID),
  TYPE            NVARCHAR(20)  NOT NULL  CHECK (TYPE IN ('IN','OUT','ADJUSTMENT','TRANSFER','SALE','RETURN')),
  QUANTITY        DECIMAL(18,4) NOT NULL,
  QUANTITY_BEFORE DECIMAL(18,4)     NULL,
  QUANTITY_AFTER  DECIMAL(18,4)     NULL,
  REASON          NVARCHAR(500)     NULL,
  REFERENCE_ID    NVARCHAR(36)      NULL,  -- SALE_ID / PURCHASE_ORDER_ID / TRANSFER_ID
  PERFORMED_BY_ID NVARCHAR(36)  NOT NULL  REFERENCES USERS(ID),
  CREATED_AT      DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_STOCK_MOVEMENTS_PRODUCT_ID ON STOCK_MOVEMENTS(PRODUCT_ID);
CREATE INDEX IX_STOCK_MOVEMENTS_BRANCH_ID  ON STOCK_MOVEMENTS(BRANCH_ID);
CREATE INDEX IX_STOCK_MOVEMENTS_TYPE       ON STOCK_MOVEMENTS(TYPE);
CREATE INDEX IX_STOCK_MOVEMENTS_CREATED_AT ON STOCK_MOVEMENTS(CREATED_AT DESC);
GO

-- ── Customers ─────────────────────────────────────────────────
CREATE TABLE CUSTOMERS (
  ID           NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  NIT          NVARCHAR(30)  NOT NULL  UNIQUE,
  NAME         NVARCHAR(150) NOT NULL,
  EMAIL        NVARCHAR(150)     NULL,
  PHONE        NVARCHAR(30)      NULL,
