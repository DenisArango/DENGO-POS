-- ============================================================
--  SECTION 3 – SALES
-- ============================================================

CREATE TABLE SALES (
  ID               NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  INVOICE_NUMBER   NVARCHAR(50)  NOT NULL  UNIQUE,
  BRANCH_ID        NVARCHAR(36)  NOT NULL  REFERENCES BRANCHES(ID),
  CASHIER_ID       NVARCHAR(36)  NOT NULL  REFERENCES USERS(ID),
  CUSTOMER_ID      NVARCHAR(36)      NULL  REFERENCES CUSTOMERS(ID),
  CASH_REGISTER_ID NVARCHAR(36)      NULL  REFERENCES CASH_REGISTERS(ID),
  SUBTOTAL         DECIMAL(18,2) NOT NULL,
  TAX              DECIMAL(18,2) NOT NULL  DEFAULT 0,
  DISCOUNT         DECIMAL(18,2) NOT NULL  DEFAULT 0,
  TOTAL            DECIMAL(18,2) NOT NULL,
  PAYMENT_METHOD   NVARCHAR(20)  NOT NULL  CHECK (PAYMENT_METHOD IN ('CASH','CARD','TRANSFER','MIXED','CREDIT')),
  SALE_TYPE        NVARCHAR(10)  NOT NULL  CHECK (SALE_TYPE IN ('CASH','CREDIT')),
  DUE_DATE         DATETIME2(7)      NULL,
  IS_PAID          BIT           NOT NULL  DEFAULT 1,
  PAID_AMOUNT      DECIMAL(18,2)     NULL,
  IS_VOIDED        BIT           NOT NULL  DEFAULT 0,
  VOIDED_BY_ID     NVARCHAR(36)      NULL  REFERENCES USERS(ID),
  VOIDED_AT        DATETIME2(7)      NULL,
  NOTES            NVARCHAR(MAX)     NULL,
  CREATED_AT       DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_SALES_BRANCH_ID        ON SALES(BRANCH_ID);
CREATE INDEX IX_SALES_CASHIER_ID       ON SALES(CASHIER_ID);
CREATE INDEX IX_SALES_CUSTOMER_ID      ON SALES(CUSTOMER_ID);
CREATE INDEX IX_SALES_CREATED_AT       ON SALES(CREATED_AT DESC);
CREATE INDEX IX_SALES_SALE_TYPE        ON SALES(SALE_TYPE);
CREATE INDEX IX_SALES_PAYMENT_METHOD   ON SALES(PAYMENT_METHOD);
CREATE INDEX IX_SALES_CASH_REGISTER_ID ON SALES(CASH_REGISTER_ID);
GO

CREATE TABLE SALE_ITEMS (
  ID           NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  SALE_ID      NVARCHAR(36)  NOT NULL  REFERENCES SALES(ID) ON DELETE CASCADE,
  PRODUCT_ID   NVARCHAR(36)  NOT NULL  REFERENCES PRODUCTS(ID),
  VARIATION_ID NVARCHAR(36)      NULL  REFERENCES PRODUCT_VARIATIONS(ID),
  QUANTITY     DECIMAL(18,4) NOT NULL,
  UNIT_PRICE   DECIMAL(18,2) NOT NULL,
