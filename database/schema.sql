-- Current stock with product info
CREATE OR ALTER VIEW VW_CURRENT_STOCK AS
SELECT
  inv.ID          AS INVENTORY_ID,
  p.ID            AS PRODUCT_ID,
  p.NAME          AS PRODUCT_NAME,
  p.BARCODE,
  p.MIN_STOCK,
  cat.NAME        AS CATEGORY_NAME,
  b.ID            AS BRANCH_ID,
  b.NAME          AS BRANCH_NAME,
  inv.QUANTITY    AS CURRENT_STOCK,
  CASE
    WHEN inv.QUANTITY <= 0           THEN 'OUT_OF_STOCK'
    WHEN inv.QUANTITY <= p.MIN_STOCK THEN 'LOW_STOCK'
    ELSE                                  'OK'
  END             AS STOCK_STATUS,
  inv.UPDATED_AT  AS LAST_UPDATED
FROM INVENTORY inv
INNER JOIN PRODUCTS p      ON p.ID = inv.PRODUCT_ID  AND p.IS_ACTIVE = 1
INNER JOIN CATEGORIES cat  ON cat.ID = p.CATEGORY_ID
INNER JOIN BRANCHES b      ON b.ID = inv.BRANCH_ID;
GO

-- Daily sales summary
CREATE OR ALTER VIEW VW_DAILY_SALES_SUMMARY AS
SELECT
  CAST(s.CREATED_AT AS DATE)  AS SALE_DATE,
  s.BRANCH_ID,
  b.NAME                      AS BRANCH_NAME,
  COUNT(s.ID)                 AS SALES_COUNT,
  SUM(s.TOTAL)                AS TOTAL_REVENUE,
  SUM(s.DISCOUNT)             AS TOTAL_DISCOUNTS,
  SUM(CASE WHEN s.PAYMENT_METHOD = 'CASH'     THEN s.TOTAL ELSE 0 END) AS CASH_REVENUE,
  SUM(CASE WHEN s.PAYMENT_METHOD = 'CARD'     THEN s.TOTAL ELSE 0 END) AS CARD_REVENUE,
  SUM(CASE WHEN s.PAYMENT_METHOD = 'TRANSFER' THEN s.TOTAL ELSE 0 END) AS TRANSFER_REVENUE
FROM SALES s
INNER JOIN BRANCHES b ON b.ID = s.BRANCH_ID
WHERE s.IS_VOIDED = 0
GROUP BY CAST(s.CREATED_AT AS DATE), s.BRANCH_ID, b.NAME;
GO

-- Top products by sales count
CREATE OR ALTER VIEW VW_TOP_PRODUCTS AS
SELECT
  p.ID              AS PRODUCT_ID,
  p.NAME            AS PRODUCT_NAME,
  cat.NAME          AS CATEGORY_NAME,
  p.BASE_PRICE,
  p.COST,
  p.SALES_COUNT,
  p.BASE_PRICE - p.COST AS MARGIN
FROM PRODUCTS p
INNER JOIN CATEGORIES cat ON cat.ID = p.CATEGORY_ID
WHERE p.IS_ACTIVE = 1;
GO

