-- ============================================================
--  SECTION 2 – CASH REGISTER
-- ============================================================

CREATE TABLE CASH_REGISTERS (
  ID              NVARCHAR(36)  NOT NULL  PRIMARY KEY,
  BRANCH_ID       NVARCHAR(36)  NOT NULL  REFERENCES BRANCHES(ID),
  OPENED_BY_ID    NVARCHAR(36)  NOT NULL  REFERENCES USERS(ID),
  CLOSED_BY_ID    NVARCHAR(36)      NULL  REFERENCES USERS(ID),
  OPENED_AT       DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  CLOSED_AT       DATETIME2(7)      NULL,
  INITIAL_AMOUNT  DECIMAL(18,2) NOT NULL,
  FINAL_AMOUNT    DECIMAL(18,2)     NULL,
  EXPECTED_AMOUNT DECIMAL(18,2)     NULL,
  DIFFERENCE      DECIMAL(18,2)     NULL,
  STATUS          NVARCHAR(10)  NOT NULL  DEFAULT 'OPEN' CHECK (STATUS IN ('OPEN','CLOSED')),
  -- Sales summary (updated via trigger/service)
  TOTAL_SALES     DECIMAL(18,2) NOT NULL  DEFAULT 0,
  SALES_COUNT     INT           NOT NULL  DEFAULT 0,
  CASH_SALES      DECIMAL(18,2) NOT NULL  DEFAULT 0,
  CARD_SALES      DECIMAL(18,2) NOT NULL  DEFAULT 0,
  TRANSFER_SALES  DECIMAL(18,2) NOT NULL  DEFAULT 0,
  CREATED_AT      DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE(),
  UPDATED_AT      DATETIME2(7)  NOT NULL  DEFAULT GETUTCDATE()
);
CREATE INDEX IX_CASH_REGISTERS_BRANCH_ID ON CASH_REGISTERS(BRANCH_ID);
CREATE INDEX IX_CASH_REGISTERS_STATUS    ON CASH_REGISTERS(STATUS);
GO

CREATE TABLE CASH_MOVEMENTS (
