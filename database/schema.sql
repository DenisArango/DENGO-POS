CREATE INDEX IX_PURCHASE_ORDERS_BRANCH_ID   ON PURCHASE_ORDERS(BRANCH_ID);
CREATE INDEX IX_PURCHASE_ORDERS_STATUS      ON PURCHASE_ORDERS(STATUS);
CREATE INDEX IX_PURCHASE_ORDERS_CREATED_AT  ON PURCHASE_ORDERS(CREATED_AT DESC);
GO

