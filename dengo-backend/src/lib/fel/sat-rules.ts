import { randomInt } from 'node:crypto'

/**
 * 2.2.1: the emission date can't be more than five days before certification
 * (counted from the day after emission). Applies to contingency documents too:
 * verified on Digifact's test environment (7 days → FEL_INF300, 5 days → OK).
 */
export const SAT_MAX_EMISSION_AGE_DAYS = 5

/** Calendar days between two instants, in Guatemala time (emission day = 0). */
export function gtCalendarDaysBetween(from: Date, to: Date): number {
  const day = (d: Date) => {
    const p = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Guatemala', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d)
    return Date.parse(`${p}T00:00:00Z`)
  }
  return Math.round((day(to) - day(from)) / 86_400_000)
}

/** Last moment a document emitted at `issuedAt` can still be certified (end of day 5, Guatemala time). */
export function contingencyDeadline(issuedAt: Date): Date {
  const p = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Guatemala', year: 'numeric', month: '2-digit', day: '2-digit' }).format(issuedAt)
  return new Date(Date.parse(`${p}T23:59:59-06:00`) + SAT_MAX_EMISSION_AGE_DAYS * 86_400_000)
}

/**
 * 5.4 (anexo, "Generación del Número de Acceso del DTE"): a random number from
 * 100000000 to 999999999 generated by the emisor's system. Uniqueness among
 * ours is enforced by the database (Sale.felAccessNumber is unique).
 */
export function generateAccessNumber(): string {
  return String(randomInt(100_000_000, 1_000_000_000))
}

export const isAccessNumber = (s: unknown): s is string => typeof s === 'string' && /^[1-9]\d{8}$/.test(s)

