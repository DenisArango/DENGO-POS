// ── Total en letras ─────────────────────────────────────────────────────────

const UNITS = ['', 'UNO', 'DOS', 'TRES', 'CUATRO', 'CINCO', 'SEIS', 'SIETE', 'OCHO', 'NUEVE', 'DIEZ', 'ONCE', 'DOCE', 'TRECE', 'CATORCE', 'QUINCE',
  'DIECISÉIS', 'DIECISIETE', 'DIECIOCHO', 'DIECINUEVE', 'VEINTE', 'VEINTIUNO', 'VEINTIDÓS', 'VEINTITRÉS', 'VEINTICUATRO', 'VEINTICINCO',
  'VEINTISÉIS', 'VEINTISIETE', 'VEINTIOCHO', 'VEINTINUEVE']
const TENS = ['', '', '', 'TREINTA', 'CUARENTA', 'CINCUENTA', 'SESENTA', 'SETENTA', 'OCHENTA', 'NOVENTA']
const HUNDREDS = ['', 'CIENTO', 'DOSCIENTOS', 'TRESCIENTOS', 'CUATROCIENTOS', 'QUINIENTOS', 'SEISCIENTOS', 'SETECIENTOS', 'OCHOCIENTOS', 'NOVECIENTOS']

function below1000(n: number): string {
  if (n === 100) return 'CIEN'
  const h = Math.floor(n / 100), r = n % 100
  const head = HUNDREDS[h] ?? ''
  let tail = ''
  if (r < 30) tail = UNITS[r] ?? ''
  else tail = `${TENS[Math.floor(r / 10)]}${r % 10 ? ` Y ${UNITS[r % 10]}` : ''}`
  return [head, tail].filter(Boolean).join(' ')
}

function integerWords(n: number): string {
  if (n === 0) return 'CERO'
  const parts: string[] = []
  const millions = Math.floor(n / 1_000_000)
  const thousands = Math.floor((n % 1_000_000) / 1000)
  const rest = n % 1000
  if (millions) parts.push(millions === 1 ? 'UN MILLÓN' : `${integerWords(millions).replace(/UNO$/, 'UN')} MILLONES`)
  if (thousands) parts.push(thousands === 1 ? 'MIL' : `${below1000(thousands).replace(/UNO$/, 'UN')} MIL`)
  if (rest) parts.push(below1000(rest))
  return parts.join(' ')
}

/** 1610.5 → "UN MIL SEISCIENTOS DIEZ QUETZALES CON 50/100" style, as Guatemalan invoices print it. */
export function amountInWords(amount: number, currency = 'GTQ'): string {
  const cents = Math.round(amount * 100)
  const int = Math.floor(cents / 100)
  const dec = cents % 100
  const word = currency === 'USD' ? (int === 1 ? 'DÓLAR' : 'DÓLARES') : (int === 1 ? 'QUETZAL' : 'QUETZALES')
  const words = integerWords(int).replace(/UNO$/, 'UN')
  return `${words} ${word} CON ${String(dec).padStart(2, '0')}/100`
}
