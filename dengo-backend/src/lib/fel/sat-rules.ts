const VERIFIER = 'https://portal.sat.gob.gt/portal/verificador-integrado/'

/** 2.22.1 — QR for a certified DTE (optional for emisores that use a certifier). */
export function certifiedQrUrl(emisorNit: string, serie: string, numero: string): string {
  return `${VERIFIER}?tipo=autorizacion&documento=FEL&emisor=${encodeURIComponent(emisorNit)}&serie=${encodeURIComponent(serie)}&numero=${encodeURIComponent(numero)}`
}

/** 2.22.2 — QR for a document emitted in contingency. */
export function contingencyQrUrl(accessNumber: string, emisorNit: string, receptorId: string, total: number): string {
  return `${VERIFIER}?tipo=contingencia&numero=${accessNumber}&emisor=${encodeURIComponent(emisorNit)}&receptor=${encodeURIComponent(receptorId)}&monto=${total.toFixed(2)}`
}

