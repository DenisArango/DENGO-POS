// What a printed factura needs that isn't on the sale itself: the emisor's
// SAT name/NIT, its frases, and whether the certifier supports contingency.
// Cached in IndexedDB so the POS can print a "Documento en contingencia"
// while the server is unreachable.

import { useEffect, useState } from 'react'
import { api } from './api'
import { getCache, setCache } from './offlineDb'

export interface FelReceiptInfo {
  enabled: boolean
  contingency: boolean
  emisorNit: string | null
  emisorName: string | null
  phrases: string[]
}

const KEY = 'fel-receipt-info'
let memo: FelReceiptInfo | null = null

export function useFelReceiptInfo(active = true): FelReceiptInfo | null {
  const [info, setInfo] = useState<FelReceiptInfo | null>(memo)
  useEffect(() => {
    if (!active) return
    let alive = true
    getCache<FelReceiptInfo>(KEY).then(c => { if (alive && c && !memo) setInfo(c) }).catch(() => {})
    api.get<FelReceiptInfo>('/api/fel/receipt-info')
      .then(r => { memo = r; if (alive) setInfo(r); setCache(KEY, r).catch(() => {}) })
      .catch(() => {}) // offline: the cached copy stands
    return () => { alive = false }
  }, [active])
  return info
}

/**
 * SAT "Reglas y validaciones FEL" 5.4: the Número de Acceso is a random number
 * from 100000000 to 999999999 generated by the emisor's system.
 */
export function generateAccessNumber(): string {
  const buf = new Uint32Array(1)
  crypto.getRandomValues(buf)
  return String(100_000_000 + (buf[0]! % 900_000_000))
}

/** Receipt fields for the emisor, phrases and contingency data of a sale. */
export function felReceiptFields(info: FelReceiptInfo | null, sale: { felAccessNumber?: string | null; felIssuedAt?: string | null }) {
  return {
    felAccessNumber: sale.felAccessNumber ?? null,
    felIssuedAt: sale.felIssuedAt ?? null,
    felPhrases: info?.phrases ?? [],
    felEmisorName: info?.emisorName ?? null,
    felEmisorNit: info?.emisorNit ?? null,
  }
}
