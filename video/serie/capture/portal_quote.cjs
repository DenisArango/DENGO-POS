// Quote PED-2026-006 from its row, then send the quotation to the teacher. Records it.
const path = require('path')
const L = require('./lib.cjs')
const ORDER = 'PED-2026-006'
;(async () => {
  const b = await L.launch(L.DESKTOP), p = await b.newPage()
  p.on('dialog', d => d.accept())
  await p.goto(L.POS + '/login', { waitUntil: 'networkidle0' })
  await p.evaluate(id => localStorage.setItem('selectedStoreId', id), 'cmvtxvvzj00007zd5m6bn27p4')
  await L.loginPos(p)
  await p.goto(L.POS + '/portal/orders', { waitUntil: 'networkidle0' }); await L.sleep(3000)
  const rec = await p.screencast({ path: path.join(L.OUT, 'pa_cotizar.webm') })
  await L.sleep(800)
  const row = () => p.$$(`xpath/.//tr[contains(., "${ORDER}")]`).then(r => r[0])
  await (await (await row()).$('button[title="Crear cotización"]')).click(); await L.sleep(2200)
  await L.shot(p, 'pa_cotizar_modal')
  await p.type('input[placeholder="Buscar cliente por nombre o NIT…"]', 'EORM Cant', { delay: 80 }); await L.sleep(1200)
  for (const s of await p.$$('select')) {
    const opts = await s.$$eval('option', os => os.map(o => [o.value, o.textContent.trim()]))
    const pick = opts.find(o => /Central/.test(o[1])) || opts.find(o => /EORM Cantón/.test(o[1]))
    if (pick) await s.select(pick[0])
  }
  await L.sleep(800)
  await L.shot(p, 'pa_cotizar_lleno')
  const btns = await p.$$('xpath/.//div[contains(@class,"fixed")]//button[not(contains(., "Cancelar"))][contains(., "Cotizaci") or contains(., "Crear")]')
  await btns[btns.length - 1].click(); await L.sleep(3000)
  await L.shot(p, 'pa_cotizado')
  await (await (await row()).$('button[title="Ver detalle"]')).click(); await L.sleep(2200)
  await L.shot(p, 'pa_detalle_cotizado')
  await L.clickText(p, 'Enviar cotización al maestro', 'button', { wait: 3000 })
  await L.shot(p, 'pa_enviada')
  await L.sleep(1000)
  await rec.stop()
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
