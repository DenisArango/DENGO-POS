// COT-2026-002: mark accepted, convert to sale (stock at Central drops by 2). Records it.
const path = require('path')
const L = require('./lib.cjs')
const QUOTE = 'COT-2026-002'
;(async () => {
  const b = await L.launch(L.DESKTOP), p = await b.newPage()
  p.on('dialog', d => d.accept())
  await p.goto(L.POS + '/login', { waitUntil: 'networkidle0' })
  await p.evaluate(id => localStorage.setItem('selectedStoreId', id), 'cmvtxvvzj00007zd5m6bn27p4')
  await L.loginPos(p)
  await p.goto(L.POS + '/quotations', { waitUntil: 'networkidle0' }); await L.sleep(3000)
  await L.shot(p, 'q_lista')
  const rec = await p.screencast({ path: path.join(L.OUT, 'q_convertir.webm') })
  await L.sleep(800)
  const row = () => p.$$(`xpath/.//tr[contains(., "${QUOTE}")]`).then(r => r[0])
  const acc = await (await row()).$('button[title="Aceptada"]')
  if (acc) { await acc.click(); await L.sleep(2500) } else console.log('no accept button')
  await L.shot(p, 'q_aceptada')
  const conv = await (await row()).$('button[title="Convertir a venta"]')
  await conv.click(); await L.sleep(3500)
  await L.shot(p, 'q_convertida')
  await L.sleep(800)
  await rec.stop()
  await b.close()
})().catch(e => { console.error(e); process.exit(1) })
